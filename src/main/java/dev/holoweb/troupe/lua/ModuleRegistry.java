package dev.holoweb.troupe.lua;

import dev.holoweb.troupe.api.AsyncFunction;
import dev.holoweb.troupe.api.Module;
import dev.holoweb.troupe.api.ModuleFunction;
import dev.holoweb.troupe.api.Modules;
import dev.holoweb.troupe.api.Side;
import dev.holoweb.troupe.api.Type;
import dev.holoweb.troupe.net.Protocol;

import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.Executor;
import java.util.function.BiConsumer;
import java.util.function.Consumer;
import java.util.function.Function;
import java.util.function.Supplier;

/** The modules of one side; mods fill it through their {@code troupe*} entrypoints. */
public final class ModuleRegistry implements Modules {
    private final Side side;
    private final Executor executor;
    private final Supplier<Collection<LuaRuntime>> running;
    private final ResourceHost host;
    private final Map<String, ModuleImpl> modules = new ConcurrentHashMap<>();
    private final Map<Class<?>, TypeImpl<?>> types = new ConcurrentHashMap<>();
    private final Map<Class<?>, Function<Object, Object>> toLua = new ConcurrentHashMap<>();
    private final Map<Class<?>, Function<Object, ?>> fromLua = new ConcurrentHashMap<>();
    private final Map<Class<?>, String> luaNames = new ConcurrentHashMap<>();
    private final Map<String, Sig> handleSigs = new ConcurrentHashMap<>();
    private static final org.slf4j.Logger LOG = org.slf4j.LoggerFactory.getLogger("troupe");
    /** "player" / "entity" → the methods mods added to those handles. */
    final Map<String, Map<String, ModuleFunction>> handleMethods = Map.of("player", new ConcurrentHashMap<>(), "entity", new ConcurrentHashMap<>());

    ModuleRegistry(Side side, Executor executor, Supplier<Collection<LuaRuntime>> running, ResourceHost host) {
        this.side = side;
        this.executor = executor;
        this.running = running;
        this.host = host;
        convert(java.util.UUID.class, Object::toString, v -> v instanceof String s ? java.util.UUID.fromString(s) : null);
        convert(java.util.Optional.class, o -> o.orElse(null));
        convert(Enum.class, e -> e.name().toLowerCase(java.util.Locale.ROOT));
    }

    // ---- types and conversions (see Modules)

    @Override
    @SuppressWarnings("unchecked")
    public <T> Type<T> type(Class<T> type, String name) {
        return (Type<T>) types.computeIfAbsent(type, c -> {
            TypeImpl<T> impl = new TypeImpl<>(type, name);
            impl.registry = this;
            Annotated.scan(impl, this);
            return impl;
        });
    }

    @Override
    public Module module(String name, Object api) {
        ModuleImpl m = (ModuleImpl) module(name);
        for (java.lang.reflect.Method method : api.getClass().getMethods()) {
            if (!method.isAnnotationPresent(dev.holoweb.troupe.api.LuaFunction.class)) continue;
            String fn = Annotated.name(method);
            Annotated.Call call = Annotated.call(method);
            if (Annotated.async(method)) m.async(fn, a -> (java.util.concurrent.CompletionStage<?>) call.call(api, a));
            else m.function(fn, a -> call.call(api, a));
            m.reflected.put(fn, method);
        }
        return m;
    }

    /** One value as the arguments of a call nobody made (a property being set). */
    dev.holoweb.troupe.api.Args args(Object value) {
        return new dev.holoweb.troupe.api.Args(null, side, java.util.Collections.singletonList(value), this::as);
    }

    /** Whether Lua can hold {@code o} (its contents aside): what a listener passes on, the rest becomes nil. */
    private boolean passable(Object o) {
        return o == null || o instanceof Boolean || o instanceof Number || o instanceof CharSequence || o instanceof Peer
                || o instanceof EntityRef || o instanceof Map || o instanceof Iterable || o instanceof Object[]
                || converter(o.getClass()) != null || typeOf(o.getClass()) != null;
    }

    /**
     * LuaLS definitions ({@code ---@meta}) of what mods added on this side: their modules, types and handle methods.
     * Troupe's own API is described by the files in {@code /troupe/defs}.
     */
    public String stubs() {
        StringBuilder out = new StringBuilder("---@meta\n-- Generated by Troupe (" + side.folder() + " side) from the mods installed here. Regenerate after adding mods.\n\n");
        types.values().stream().sorted(java.util.Comparator.comparing(t -> t.name)).forEach(t -> {
            String id = t.name.replaceAll("[^A-Za-z0-9_.]", "_"), local = id.replace('.', '_') + "_";
            out.append("---@class ").append(id).append('\n');
            new java.util.TreeSet<>(t.getters.keySet()).forEach(p -> {
                Object type = t.propertyTypes.get(p);
                out.append("---@field ").append(p).append(' ').append(type instanceof Class<?> c ? Annotated.luaType(c, this) : type == null ? "any" : type).append('\n');
            });
            out.append("local ").append(local).append(" = {}\n");
            new java.util.TreeSet<>(t.methods.keySet()).forEach(fn -> Sig.declare(out, local, ':', fn,
                    t.sigs.containsKey(fn) ? t.sigs.get(fn) : t.reflected.containsKey(fn) ? Sig.of(t.reflected.get(fn), this) : null));
            out.append('\n');
        });
        handleMethods.forEach((kind, methods) -> {
            if (methods.isEmpty()) return;
            String cls = kind.equals("player") ? "Player" : "Entity";
            out.append("---@class ").append(cls).append("\nlocal ").append(cls).append("_ = {}\n");
            new java.util.TreeSet<>(methods.keySet()).forEach(fn -> Sig.declare(out, cls + "_", ':', fn, handleSigs.get(kind + ":" + fn)));
            out.append('\n');
        });
        List<ModuleImpl> mods = modules.values().stream().filter(m -> !m.global && !m.name.contains("-")).sorted(java.util.Comparator.comparing(m -> m.name)).toList();
        StringBuilder on = new StringBuilder();
        for (ModuleImpl m : mods) {
            String owner = "mod_" + m.name;
            out.append("---@class mods.").append(m.name).append("\nlocal ").append(owner).append(" = {}\n");
            java.util.TreeSet<String> fns = new java.util.TreeSet<>(m.functions.keySet());
            fns.addAll(m.async.keySet());
            fns.forEach(fn -> Sig.declare(out, owner, '.', fn, m.sig(fn, this)));
            new java.util.TreeSet<>(m.events).forEach(e -> on.append("---@overload fun(name: \"").append(m.name).append("\", event: \"").append(e)
                    .append("\", handler: ").append(m.eventSigs.containsKey(e) ? m.eventSigs.get(e).funType() : "function").append(")\n"));
            out.append('\n');
        }
        for (ModuleImpl m : mods) out.append("---@overload fun(name: \"").append(m.name).append("\"): mods.").append(m.name).append('\n');
        out.append("---@param name string\n---@return table\nfunction mods.get(name) end\n\n");
        out.append(on).append("---@param name string\n---@param event string\n---@param handler function\nfunction mods.on(name, event, handler) end\n");
        return out.toString();
    }

    /** {@code module.fn} and {@code module.on_event} of every module of Troupe's own on this side, sorted. */
    public List<String> globalFunctions() {
        java.util.TreeSet<String> out = new java.util.TreeSet<>();
        for (ModuleImpl m : modules.values()) {
            if (!m.global) continue;
            for (String fn : m.functions.keySet()) out.add(m.name + "." + fn);
            for (String fn : m.async.keySet()) out.add(m.name + "." + fn);
            for (String e : m.events) out.add(m.name + ".on_" + e);
        }
        return List.copyOf(out);
    }

    boolean hasType(String name) {
        for (TypeImpl<?> t : types.values()) if (t.name.equals(name)) return true;
        return false;
    }

    /** Troupe's glue: what editors should call a converted class ({@code ServerPlayer} is a {@code Player}). */
    public void luaName(Class<?> type, String name) {
        luaNames.put(type, name);
    }

    String luaName(Class<?> type) {
        return find(luaNames, type);
    }

    @Override
    public <T> void convert(Class<T> type, Function<? super T, Object> to) {
        toLua.put(type, o -> to.apply(type.cast(o)));
    }

    @Override
    public <T> void convert(Class<T> type, Function<? super T, Object> to, Function<Object, ? extends T> from) {
        convert(type, to);
        fromLua.put(type, from);
    }

    @Override
    public void method(String kind, String name, ModuleFunction function) {
        Map<String, ModuleFunction> methods = handleMethods.get(kind);
        if (methods == null) throw new IllegalArgumentException("methods go on \"player\" or \"entity\", not \"" + kind + "\"");
        methods.put(name, function);
    }

    @Override
    public void method(String kind, String name, String signature, ModuleFunction function) {
        Sig sig = Sig.parse(signature);
        method(kind, name, a -> {
            sig.check(a, 1, this);
            return function.call(a);
        });
        handleSigs.put(kind + ":" + name, sig);
    }

    @Override
    public void onStart(Consumer<String> listener) {
        host.onStart(listener);
    }

    @Override
    public void onStop(Consumer<String> listener) {
        host.onStop(listener);
    }

    /** The entry for {@code c}: its own, a superclass's, then any interface's. ponytail: no cache, the maps are small. */
    private static <V> V find(Map<Class<?>, V> map, Class<?> c) {
        for (Class<?> k = c; k != null; k = k.getSuperclass()) {
            V v = map.get(k);
            if (v != null) return v;
        }
        for (Map.Entry<Class<?>, V> e : map.entrySet()) if (e.getKey().isAssignableFrom(c)) return e.getValue();
        return null;
    }

    Function<Object, Object> converter(Class<?> c) {
        return find(toLua, c);
    }

    TypeImpl<?> typeOf(Class<?> c) {
        return find(types, c);
    }

    /** {@link dev.holoweb.troupe.api.Args#as}: {@code v} as {@code type}, or null when it isn't one. */
    Object as(Object v, Class<?> type) {
        if (type.isInstance(v)) return v;
        if (type.isEnum() && v instanceof String s) {
            for (Object c : type.getEnumConstants()) if (((Enum<?>) c).name().equalsIgnoreCase(s)) return c;
            return null;
        }
        // Its own converter, or one of a supertype whose result happens to be one (Entity's for LivingEntity).
        for (Map.Entry<Class<?>, Function<Object, ?>> e : fromLua.entrySet()) {
            if (!e.getKey().isAssignableFrom(type)) continue;
            Object out = e.getValue().apply(v);
            if (type.isInstance(out)) return out;
        }
        return null;
    }

    static final class TypeImpl<T> implements Type<T> {
        final Class<T> type;
        final String name;
        final Map<String, Method<T>> methods = new ConcurrentHashMap<>();
        final Map<String, Function<? super T, Object>> getters = new ConcurrentHashMap<>();
        final Map<String, BiConsumer<? super T, Object>> setters = new ConcurrentHashMap<>();
        /** Annotated members keep what reflection knows, for the LuaLS definitions. */
        final Map<String, java.lang.reflect.Method> reflected = new ConcurrentHashMap<>();
        /** A Class (reflection) or the Lua type as declared. */
        final Map<String, Object> propertyTypes = new ConcurrentHashMap<>();
        final Map<String, Sig> sigs = new ConcurrentHashMap<>();
        ModuleRegistry registry;

        @Override
        public Type<T> method(String method, String signature, Method<T> function) {
            Sig sig = Sig.parse(signature);
            sigs.put(method, sig);
            return method(method, (self, a) -> {
                sig.check(a, 0, registry);
                return function.call(self, a);
            });
        }

        @Override
        public Type<T> property(String property, String type, Function<? super T, Object> get) {
            propertyTypes.put(property, type);
            return property(property, get);
        }

        @Override
        public Type<T> property(String property, String type, Function<? super T, Object> get, BiConsumer<? super T, Object> set) {
            propertyTypes.put(property, type);
            return property(property, get, (o, v) -> {
                if (!Sig.fits(type, v, registry)) throw new IllegalArgumentException(type + " expected, got " + Sig.typeName(v, registry));
                set.accept(o, v);
            });
        }

        TypeImpl(Class<T> type, String name) {
            this.type = type;
            this.name = name;
        }

        @Override
        public String name() {
            return name;
        }

        @Override
        public Type<T> method(String method, Method<T> function) {
            methods.put(method, function);
            return this;
        }

        @Override
        public Type<T> property(String property, Function<? super T, Object> get) {
            getters.put(property, get);
            return this;
        }

        @Override
        public Type<T> property(String property, Function<? super T, Object> get, BiConsumer<? super T, Object> set) {
            setters.put(property, set);
            return property(property, get);
        }
    }

    @Override
    public Side side() {
        return side;
    }

    @Override
    public Module module(String name) {
        if (!Protocol.validName(name)) throw new IllegalArgumentException("bad module name '" + name + "': use a-z, 0-9, '_' and '-'");
        return modules.computeIfAbsent(name, ModuleImpl::new);
    }

    /**
     * Troupe's own API: a module every resource of this side also sees as the global {@code name}, with
     * {@code name.on_<event>(fn)} for each event. Not in {@link Modules}: mods get {@code mods.*}, never globals.
     */
    public Module global(String name) {
        ModuleImpl m = (ModuleImpl) module(name);
        m.global = true;
        return m;
    }

    /** The mod modules and their versions ("" when they declare none), sorted. */
    public Map<String, String> modVersions() {
        Map<String, String> out = new java.util.TreeMap<>();
        for (ModuleImpl m : modules.values()) if (!m.global) out.put(m.name, m.version == null ? "" : m.version);
        return out;
    }

    /** What a mod module says scripts can do through it ({@link Module#describe}), or null. */
    public String description(String name) {
        ModuleImpl m = modules.get(name);
        return m == null ? null : m.description;
    }

    /** The modules mods registered (what {@code mods.*} reaches), sorted. */
    public java.util.List<String> modNames() {
        return modules.values().stream().filter(m -> !m.global).map(m -> m.name).sorted().toList();
    }

    java.util.List<ModuleImpl> globals() {
        return modules.values().stream().filter(m -> m.global).toList();
    }

    /** Delivers a module event to one resource only (e.g. players.join for players already online when it starts). */
    public void emitTo(String resource, Module module, String event, Object... args) {
        ModuleImpl m = (ModuleImpl) module;
        if (!m.events.contains(event)) throw new IllegalArgumentException("module '" + m.name + "' has no event '" + event + "'");
        Object[] copy = args.clone();
        m.checkEvent(event, copy);
        executor.execute(() -> {
            for (LuaRuntime r : running.get()) if (r.name().equals(resource)) r.dispatch(m.name, event, copy);
        });
    }

    /** Whether any running resource handles {@code module.on_<event>}: skip building the arguments when none does. */
    public boolean listens(Module module, String event) {
        String m = module.name();
        for (LuaRuntime r : running.get()) if (r.listens(m, event)) return true;
        return false;
    }

    /**
     * A cancellable event, on the calling (game) thread: every handler runs now and returning {@code false} from one
     * cancels. @return true when nothing cancelled
     */
    public boolean emitCancellable(Module module, String event, Object... args) {
        ModuleImpl m = (ModuleImpl) module;
        if (!m.events.contains(event)) throw new IllegalArgumentException("module '" + m.name + "' has no event '" + event + "'");
        boolean allowed = true;
        m.checkEvent(event, args);
        for (LuaRuntime r : List.copyOf(running.get())) allowed &= r.dispatchCancellable(m.name, event, args.clone());
        return allowed;
    }

    ModuleImpl find(String name) {
        return modules.get(name);
    }

    public boolean has(String name) {
        return modules.containsKey(name);
    }

    final class ModuleImpl implements Module {
        private final String name;
        private final Map<String, ModuleFunction> functions = new ConcurrentHashMap<>();
        private final Map<String, AsyncFunction> async = new ConcurrentHashMap<>();
        private final Map<String, java.lang.reflect.Method> reflected = new ConcurrentHashMap<>();
        private final Map<String, Sig> sigs = new ConcurrentHashMap<>(), eventSigs = new ConcurrentHashMap<>();
        private final Set<String> warned = ConcurrentHashMap.newKeySet();

        Sig sig(String fn, ModuleRegistry registry) {
            Sig declared = sigs.get(fn);
            return declared != null ? declared : reflected.containsKey(fn) ? Sig.of(reflected.get(fn), registry) : null;
        }

        @Override
        public Module function(String fn, String signature, ModuleFunction function) {
            Sig sig = Sig.parse(signature);
            sigs.put(fn, sig);
            return function(fn, a -> {
                sig.check(a, 0, ModuleRegistry.this);
                return function.call(a);
            });
        }

        @Override
        public Module async(String fn, String signature, AsyncFunction function) {
            Sig sig = Sig.parse(signature);
            sigs.put(fn, sig);
            return async(fn, a -> {
                sig.check(a, 0, ModuleRegistry.this);
                return function.call(a);
            });
        }

        @Override
        public Module event(String event, String signature) {
            eventSigs.put(event, Sig.parse(signature));
            return event(event);
        }

        /** A mod emitting what it didn't declare is its bug: say so once, deliver anyway. */
        void checkEvent(String event, Object[] args) {
            Sig sig = eventSigs.get(event);
            if (sig == null || warned.contains(event)) return;
            try {
                sig.check(args.length, i -> {
                    Object o = args[i];
                    Function<Object, Object> converter = o == null || o instanceof Map || o instanceof Iterable ? null : converter(o.getClass());
                    return converter == null ? o : converter.apply(o);
                }, ModuleRegistry.this);
            } catch (IllegalArgumentException e) {
                if (warned.add(event)) LOG.warn("Event {}.{} was emitted with arguments its signature doesn't describe: {}", name, event, e.getMessage());
            }
        }
        private final Set<String> events = ConcurrentHashMap.newKeySet();
        volatile boolean global;
        volatile String version, description;

        @Override
        public Module version(String v) {
            version = v;
            return this;
        }

        @Override
        public Module describe(String text) {
            description = text;
            return this;
        }

        String version() {
            return version;
        }

        ModuleImpl(String name) {
            this.name = name;
        }

        @Override
        public String name() {
            return name;
        }

        @Override
        public Module function(String fn, ModuleFunction function) {
            functions.put(fn, function);
            return this;
        }

        @Override
        public Module async(String fn, AsyncFunction function) {
            async.put(fn, function);
            return this;
        }

        AsyncFunction async(String fn) {
            return async.get(fn);
        }

        Set<String> asyncNames() {
            return async.keySet();
        }

        @Override
        public <T> T listener(String event, Class<T> type) {
            return listener(event, type, null);
        }

        @Override
        public <T> T listener(String event, Class<T> type, Object result) {
            if (!type.isInterface()) throw new IllegalArgumentException(type.getName() + " isn't an interface");
            event(event);
            return type.cast(java.lang.reflect.Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[]{type}, (proxy, method, args) -> {
                if (method.getDeclaringClass() == Object.class) return switch (method.getName()) {
                    case "equals" -> proxy == args[0];
                    case "hashCode" -> System.identityHashCode(proxy);
                    default -> "listener of " + name + "." + event;
                };
                if (method.isDefault()) return java.lang.reflect.InvocationHandler.invokeDefault(proxy, method, args);
                Object[] values = args == null ? new Object[0] : args.clone();
                for (int i = 0; i < values.length; i++) if (!passable(values[i])) values[i] = null;
                Class<?> r = method.getReturnType();
                if (r == boolean.class && result == null) return emitCancellable(this, event, values);
                emit(event, values);
                if (result != null || !r.isPrimitive() || r == void.class) return result;
                return r == boolean.class ? (Object) true : r == long.class ? (Object) 0L : r == float.class ? (Object) 0f : r == double.class ? (Object) 0d : (Object) 0;
            }));
        }

        @Override
        public Module event(String event) {
            events.add(event);
            return this;
        }

        @Override
        public void emit(String event, Object... args) {
            if (!events.contains(event)) throw new IllegalArgumentException("module '" + name + "' has no event '" + event + "'");
            Object[] copy = args.clone();
            checkEvent(event, copy);
            executor.execute(() -> {
                for (LuaRuntime r : running.get()) r.dispatch(name, event, copy);
            });
        }

        ModuleFunction function(String fn) {
            return functions.get(fn);
        }

        Set<String> functionNames() {
            return functions.keySet();
        }

        Set<String> eventNames() {
            return events;
        }

        boolean hasEvent(String event) {
            return events.contains(event);
        }
    }
}
